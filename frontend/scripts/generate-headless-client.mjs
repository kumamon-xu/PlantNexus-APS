import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(
  frontendRoot,
  "../backend/app/api/openapi/headless-api.v1.json",
);
const targetPath = resolve(
  frontendRoot,
  "src/headless/generated/headless-api.v1.ts",
);

const expectedOperations = [
  ["createHeadlessPlanningRun", "POST", "/api/v1/planning-runs"],
  [
    "getHeadlessPlanningRunStatus",
    "GET",
    "/api/v1/planning-runs/{planning_run_id}/status",
  ],
  [
    "cancelHeadlessPlanningRun",
    "POST",
    "/api/v1/planning-runs/{planning_run_id}/cancel",
  ],
  [
    "retryHeadlessPlanningRun",
    "POST",
    "/api/v1/planning-runs/{planning_run_id}/retry",
  ],
  [
    "getHeadlessPlanningRunResult",
    "GET",
    "/api/v1/planning-runs/{planning_run_id}/result",
  ],
];
const expectedSchemas = [
  "CanonicalIngressRequest",
  "CanonicalIngressResult",
  "HeadlessError",
  "PlanningRun",
  "PlanningRunCancelAction",
  "PlanningRunRetryAction",
  "PlanningWorkspaceErrorEnvelope",
];

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function sha256(value) {
  return `sha256:${createHash("sha256").update(value).digest("hex")}`;
}

function requireObject(value, label) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} is not an object`);
  }
  return value;
}

const source = readFileSync(sourcePath);
const document = requireObject(JSON.parse(source.toString("utf8")), "OpenAPI");
const paths = requireObject(document.paths, "OpenAPI paths");
const schemas = requireObject(
  requireObject(document.components, "OpenAPI components").schemas,
  "OpenAPI schemas",
);
const contract = requireObject(
  document["x-aps-headless-contract"],
  "x-aps-headless-contract",
);

if (
  contract.http_contract_version !== "headless-http.v1" ||
  contract.compatibility_policy !== "V1_ADDITIVE_ONLY" ||
  contract.headless_operation_count !== 5 ||
  contract.total_operation_count !== 34
) {
  throw new Error("P8-07 Headless OpenAPI boundary drifted");
}

const operations = expectedOperations.map(([operationId, method, path]) => {
  const operation = requireObject(
    requireObject(paths[path], `path ${path}`)[method.toLowerCase()],
    `${method} ${path}`,
  );
  if (operation.operationId !== operationId) {
    throw new Error(`${method} ${path} operationId drifted`);
  }
  const responses = requireObject(operation.responses, `${operationId} responses`);
  const successStatus = Object.keys(responses)
    .filter((value) => /^2\d\d$/u.test(value))
    .sort()[0];
  if (successStatus === undefined) {
    throw new Error(`${operationId} has no success response`);
  }
  return { method, operationId, path, successStatus: Number(successStatus) };
});

const schemaDigests = Object.fromEntries(
  expectedSchemas.map((name) => {
    if (!(name in schemas)) throw new Error(`OpenAPI schema absent: ${name}`);
    return [name, sha256(canonical(schemas[name]))];
  }),
);

const projection = {
  apiContractVersion: contract.http_contract_version,
  compatibilityPolicy: contract.compatibility_policy,
  generatedFrom: "backend/app/api/openapi/headless-api.v1.json",
  openapiVersion: document.openapi,
  operationCount: operations.length,
  operations,
  schemaDigests,
  sourceSha256: sha256(source),
  totalOpenApiOperationCount: contract.total_operation_count,
};
const output = `// Generated by scripts/generate-headless-client.mjs. Do not edit.\n` +
  `export const headlessOpenApiContract = ${JSON.stringify(projection, null, 2)} as const;\n\n` +
  `export type HeadlessOperationId = (typeof headlessOpenApiContract.operations)[number]["operationId"];\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(targetPath) || readFileSync(targetPath, "utf8") !== output) {
    throw new Error(
      "generated Headless client metadata is stale; run npm run client:generate",
    );
  }
  process.stdout.write(
    `PASS generated Headless client metadata: ${projection.sourceSha256}\n`,
  );
} else {
  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, output, "utf8");
  process.stdout.write(`WROTE ${targetPath}\n`);
}
